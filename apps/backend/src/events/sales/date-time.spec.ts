import { parseOffsetDateTime } from './date-time';

describe('parseOffsetDateTime', () => {
  it.each([
    ['2026-10-15T15:00:00Z', '2026-10-15T15:00:00.000Z'],
    ['2026-10-15T15:00Z', '2026-10-15T15:00:00.000Z'],
    ['2026-10-15T10:00:00-05:00', '2026-10-15T15:00:00.000Z'],
    ['2026-10-16T00:30:00+09:30', '2026-10-15T15:00:00.000Z'],
    ['2026-10-15T15:00:00.123456Z', '2026-10-15T15:00:00.123Z'],
    ['2028-02-29T23:59:59Z', '2028-02-29T23:59:59.000Z'],
  ])('parses %s as the instant %s', (input, expected) => {
    expect(parseOffsetDateTime(input)?.toISOString()).toBe(expected);
  });

  it.each([
    '2026-02-31T10:00:00Z',
    '2026-02-29T10:00:00Z',
    '2026-04-31T10:00:00Z',
    '2026-13-01T00:00:00Z',
    '2026-00-10T00:00:00Z',
    '2026-10-00T00:00:00Z',
    '2026-10-15T24:00:00Z',
    '2026-10-15T23:60:00Z',
    '2026-10-15T23:59:60Z',
    '2026-10-15T10:00:00+24:00',
    '2026-10-15T10:00:00+05:60',
    '2026-10-15',
    '2026-10-15T10:00:00',
    'tomorrow',
  ])('rejects %s', (input) => {
    expect(parseOffsetDateTime(input)).toBeNull();
  });
});
